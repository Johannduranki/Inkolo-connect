import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import {HeritageStore} from '../src/heritage-store.js';
import {createHeritageRouter} from '../src/heritage-api.js';
test('HTTP authentication, private/public redaction, scope denial and protected files',async t=>{
  const store=new HeritageStore(':memory:'),scope={tenant_id:'t',community_id:'c',name:'Test'};
  const owner={id:'1',name:'Test Owner',scopes:[scope]},admin={id:'admin',platform:true,scopes:[]};
  store.configure(admin,[scope],{...scope,tenant_enabled:true,enabled:true});
  const tree=store.createTree(owner,{community_id:'c',name:'Test tree'});
  const state={users:[{id:'1',firstName:'Test',lastName:'Owner',status:'active',roles:['Member']}],memberCommunities:[{memberId:'1',tenantId:'t',communityId:'c',communityName:'Test'}]};
  const app=express();app.use(express.json());app.use('/api/heritage',createHeritageRouter({store,readState:()=>state,resolveUser:id=>state.users.find(u=>u.id===id),requireAuth:(req,res,next)=>{if(req.get('authorization')!=='Bearer fixture')return res.sendStatus(401);req.auth={sub:'1'};next();}}));
  app.use((e,req,res,next)=>res.status(500).json({message:e.message}));
  const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
  t.after(()=>{server.close();store.db.close();});const url='http://127.0.0.1:'+server.address().port+'/api/heritage';
  assert.equal((await fetch(url+'/tree?community_id=c')).status,401);
  assert.equal((await fetch(url+'/public/'+tree.person_id)).status,404);
  assert.equal((await fetch(url+'/tree?community_id=foreign',{headers:{Authorization:'Bearer fixture'}})).status,404);
  const p=store.person(owner,tree.person_id);store.updatePerson(owner,p.person_id,{...p,privacy:'Public'});
  const publicRecord=await (await fetch(url+'/public/'+p.person_id)).json();
  assert.equal(publicRecord.display_name,'Test Owner');assert.equal(publicRecord.owner_user_id,undefined);assert.equal(publicRecord.notes,undefined);
  assert.equal((await fetch(url+'/documents/unknown')).status,401);
  const bad=await fetch(url+'/configuration',{method:'PUT',headers:{Authorization:'Bearer fixture','Content-Type':'application/json'},body:JSON.stringify({...scope,enabled:true,tenant_enabled:true})});assert.equal(bad.status,403);
});
