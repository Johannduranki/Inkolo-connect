import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import express from 'express';
import jwt from 'jsonwebtoken';
import { authenticator } from '@otplib/v12-adapter';
import { MfaStore } from '../src/mfa.js';
import { createMfaRouter } from '../src/mfa-api.js';
import { requireAuth,createAccessToken } from '../src/auth.js';
import { signToken } from '../src/token-security.js';
import { SessionStore } from '../src/session-security.js';

test('MFA API enforces challenge-only enrolment and blocks unverified API sessions',async t=>{
  for(const key of ['DB_HOST','DB_USER','DB_NAME','ID_PEPPER'])process.env[key]='test';
  process.env.JWT_SECRET=randomBytes(32).toString('hex');
  const store=new MfaStore(':memory:',null,randomBytes(32));
  const admin={id:'admin',first_name:'Test',last_name:'Admin',roles:['Platform Admin'],status:'active'};
  const member={...admin,id:'member',roles:['Member']};
  const resolveUser=id=>id==='admin'?admin:member;
  const app=express();app.use(express.json());app.locals.mfa={store,resolveUser};
  app.use('/mfa',createMfaRouter({store,resolveUser}));
  app.get('/private',requireAuth,(req,res)=>res.json({ok:true}));
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  t.after(()=>{server.closeAllConnections();server.close();store.db.close();});
  const call=(path,token,body)=>fetch(`http://127.0.0.1:${server.address().port}${path}`,{method:body?'POST':'GET',headers:{authorization:'Bearer '+token,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
  const old=await createAccessToken(admin);
  assert.equal((await call('/private',old)).status,403);
  assert.equal((await call('/mfa/setup',old,{})).status,403);
  assert.equal((await call('/private',await createAccessToken(member))).status,200);
  const jti=store.begin('admin'),challenge=signToken({sub:'admin',purpose:'mfa',jti},process.env.JWT_SECRET,'10m');
  assert.equal((await call('/private',challenge)).status,403);
  const setup=await (await call('/mfa/setup',challenge,{})).json();assert.match(setup.qr,/^data:image\/png/);
  const verification=await (await call('/mfa/verify',challenge,{code:authenticator.generate(setup.secret)})).json();
  assert.equal(verification.recoveryCodes.length,8);
  assert.equal((await call('/private',verification.accessToken)).status,200);
  assert.equal((await call('/mfa/verify',challenge,{code:'000000'})).status,401);
  member.roles.push('Tenant Admin');
  assert.equal((await call('/private',await createAccessToken(member))).status,403);
});

test('MFA status respects revocation and idle expiry without extending a session',async t=>{
  for(const key of ['DB_HOST','DB_USER','DB_NAME','ID_PEPPER'])process.env[key]='test';
  process.env.JWT_SECRET=randomBytes(32).toString('hex');
  let now=Date.now();
  const sessions=new SessionStore(':memory:',()=>now),store=new MfaStore(':memory:',null,randomBytes(32));
  const member={id:'member',roles:['Member'],status:'active'},admin={id:'admin',roles:['Platform Admin'],status:'active'};
  const app=express();app.use('/mfa',createMfaRouter({store,sessions,resolveUser:id=>id==='member'?member:admin}));
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  t.after(()=>{server.closeAllConnections();server.close();sessions.close();store.db.close();});
  const status=token=>fetch(`http://127.0.0.1:${server.address().port}/mfa/status`,{headers:{Authorization:'Bearer '+token}});
  const token=await createAccessToken(member,{},sessions);
  assert.equal((await status(token)).status,200);
  now+=29*60000;assert.equal((await status(token)).status,200);
  now+=2*60000;assert.equal((await status(token)).status,401);
  const next=await createAccessToken(member,{},sessions);sessions.revokeUser(member.id);
  assert.equal((await status(next)).status,401);
  const id=store.begin(admin.id),challenge=signToken({sub:admin.id,purpose:'mfa',jti:id},process.env.JWT_SECRET,'10m');
  assert.equal((await status(challenge)).status,200);
  store.run('UPDATE challenge SET expires=0 WHERE id=?',id);
  assert.equal((await status(challenge)).status,401);
  const other=store.begin(admin.id),mismatch=signToken({sub:member.id,purpose:'mfa',jti:other},process.env.JWT_SECRET,'10m');
  assert.equal((await status(mismatch)).status,401);
});
