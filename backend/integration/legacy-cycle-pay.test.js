import { isolatedStore } from './isolated-stores.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash, createHmac } from 'node:crypto';
import express from 'express';
import { CycleStore, cycleConfig, publicCycleConfig, signCyclePayload, validCycleSignature } from '../src/cycle-pay.js';
import { createCycleRouter } from '../src/cycle-api.js';
const config = () => cycleConfig({ CYCLE_ENABLED: 'true', CYCLE_MODE: 'sandbox', CYCLE_MERCHANT_ACCOUNT: 'Fixture', CYCLE_PAYWALL_SECRET: 'fixture-paywall', CYCLE_NOTIFICATION_SECRET: 'fixture-notification', CYCLE_PUBLIC_URL: 'https://payments.example.test' });
const input = { userId: '2', tenantId: 'tenant-a', communityId: 'community-a', description: 'Fixture membership invoice', reference: 'TEST-001', amountCents: 12500 };
const event = row => ({ id: row.id, internalId: 'provider-001', merchantAccount: 'Fixture', status: 'CHARGED', lineItem: { amount: 125, currency: 'ZAR' }, amountRemaining: 0, transactions: [{ type: 'CHARGE', state: 'APPROVED', amount: 125, currency: 'ZAR' }] });
const notify = async (store, payload) => { const raw = Buffer.from(JSON.stringify(payload)); return await store.notify(raw, createHmac('sha256', config().notificationKey).update(raw).digest('hex'), config()); };
test('Cycle is disabled by default and configuration responses never reveal secrets', () => {
    assert.equal(cycleConfig({}).ready, false);
    assert.equal(config().ready, true);
    const safe = JSON.stringify(publicCycleConfig(config()));
    assert(!safe.includes('fixture-paywall'));
    assert(!safe.includes('fixture-notification'));
    assert.equal(cycleConfig({ CYCLE_MODE: 'live', CYCLE_ENABLED: 'true' }).ready, false);
    assert.equal(cycleConfig({ CYCLE_PUBLIC_URL: 'http://localhost:4200' }).ready, false);
});
test('hosted signature and callback signature follow the documented separate algorithms', () => {
    const raw = Buffer.from('{"example":1}');
    assert.equal(signCyclePayload(raw.toString(), 'test'), createHash('sha256').update('test' + raw).digest('hex'));
    const signature = createHmac('sha256', 'secret').update(raw).digest('hex');
    assert(validCycleSignature(raw, signature.toUpperCase(), 'secret'));
    assert(!validCycleSignature(Buffer.from('{}'), signature, 'secret'));
    assert(!validCycleSignature(raw, 'bad', 'secret'));
    assert(!validCycleSignature(raw, signature, ''));
});
test('checkout uses server amounts, protects ownership and refuses disabled collection', async (t) => {
    const store = await isolatedStore(t, CycleStore, 'cycle');
    const row = await store.create(input, '1', 'sandbox');
    await assert.rejects(async () => await store.checkout(row.id, '3', config()), { status: 404 });
    await assert.rejects(async () => await store.checkout(row.id, '2', cycleConfig({})), { status: 503 });
    const checkout = await store.checkout(row.id, '2', config()), payload = JSON.parse(checkout.payload);
    assert.equal(payload.price, '125.00');
    assert.equal(payload.chargeId, row.id);
    assert.equal(payload.customerId, '2');
    assert.equal((await store.request(row.id)).status, 'PENDING');
    assert(!checkout.payload.includes('fixture-paywall'));
    await assert.rejects(async () => await store.create(input, '1', 'sandbox'), { status: 409 });
});
test('tenant payment registers and summaries exclude other tenants', async (t) => {
    const store = await isolatedStore(t, CycleStore, 'cycle');
    await store.create(input, '1', 'sandbox');
    await store.create({ ...input, tenantId: 'tenant-b', reference: 'OTHER', amountCents: 700 }, '1', 'sandbox');
    assert.equal((await store.list(null, 'tenant-a')).length, 1);
    assert.equal((await store.summary('tenant-a'))[0].pending_cents, 12500);
    assert.equal((await store.summary('tenant-b'))[0].pending_cents, 700);
    assert.deepEqual(await store.list(null, 'missing'), []);
    assert.deepEqual(await store.summary('missing'), []);
});
test('verified complete charges are idempotent and mismatches never change the ledger', async (t) => {
    const store = await isolatedStore(t, CycleStore, 'cycle');
    const row = await store.create(input, '1', 'sandbox');
    await assert.rejects(async () => await notify(store, { ...event(row), merchantAccount: 'Other' }), { status: 409 });
    await assert.rejects(async () => await notify(store, { ...event(row), lineItem: { amount: 1, currency: 'ZAR' } }), { status: 409 });
    await assert.rejects(async () => await notify(store, { ...event(row), amountRemaining: 1 }), { status: 409 });
    await assert.rejects(async () => await notify(store, { ...event(row), transactions: [] }), { status: 409 });
    assert.equal((await store.request(row.id)).status, 'PENDING');
    await notify(store, event(row));
    assert.equal((await store.request(row.id)).status, 'CHARGED');
    assert.equal((await notify(store, event(row))).duplicate, true);
    assert.equal((await store.fixtureQuery('SELECT COUNT(*) n FROM cycle_event'))[0].n, 1);
    await assert.rejects(async () => await store.checkout(row.id, '2', config()), { status: 409 });
    const second = await store.create({ ...input, reference: 'TEST-002' }, '1', 'sandbox');
    await assert.rejects(async () => await notify(store, event(second)), { status: 409 });
    assert.equal((await store.request(second.id)).status, 'PENDING');
    await notify(store, { ...event(row), status: 'REFUNDED' });
    assert.equal((await store.request(row.id)).review_required, 1);
    assert.equal((await store.request(row.id)).status, 'CHARGED');
});
test('Cycle API denies members admin access, validates community membership and enforces checkout ownership', async (t) => {
    const store = await isolatedStore(t, CycleStore, 'cycle');
    const users = [{ id: '1', status: 'active', roles: ['Platform Admin'] }, { id: '2', status: 'active', roles: ['Member'] }, { id: '3', status: 'active', roles: ['Member'] }];
    const state = { users, importedCommunities: [{ id: 'community-a', tenantId: 'tenant-a', name: 'A' }], memberCommunities: [{ memberId: '2', communityId: 'community-a', tenantId: 'tenant-a' }] };
    const app = express();
    app.use('/cycle/notifications', express.raw({ type: 'application/json' }));
    app.use(express.json());
    app.use('/cycle', createCycleRouter({ store, config, readState: () => state, requireAuth: (req, res, next) => { if (!req.get('x-user'))
            return res.sendStatus(401); req.auth = { sub: req.get('x-user') }; next(); }, resolveUser: async (id) => users.find(u => u.id === id) }));
    const server = app.listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    t.after(() => { server.closeAllConnections(); server.close(); });
    const call = (path, user, body) => fetch(`http://127.0.0.1:${server.address().port}/cycle${path}`, { method: body ? 'POST' : 'GET', headers: { 'x-user': user || '', 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
    assert.equal((await call('/admin')).status, 401);
    assert.equal((await call('/admin', '2')).status, 403);
    assert.equal((await call('/requests', '2', input)).status, 403);
    assert.equal((await call('/requests', '1', { ...input, userId: '3' })).status, 400);
    const response = await call('/requests', '1', input);
    assert.equal(response.status, 201);
    const row = await response.json();
    assert.equal((await call('/requests/' + row.id + '/checkout', '3', {})).status, 404);
    assert.equal((await (await call('/requests', '3')).json()).requests.length, 0);
    assert.equal((await call('/requests/' + row.id + '/checkout', '2', {})).status, 200);
    assert.equal((await call('/notifications', null, event(row))).status, 403);
});
