USE duranki_login;

CREATE TABLE IF NOT EXISTS accounting_scope_code (
  scope_code_id VARCHAR(64) NOT NULL,
  scope_type ENUM('PLATFORM', 'TENANT', 'COMMUNITY', 'SERVICE_PROVIDER') NOT NULL,
  scope_id VARCHAR(64) NOT NULL,
  scope_name VARCHAR(180) NOT NULL,
  short_code VARCHAR(20) NOT NULL,
  status ENUM('ACTIVE', 'INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (scope_code_id),
  UNIQUE KEY uq_accounting_scope (scope_type, scope_id),
  UNIQUE KEY uq_accounting_short_code (short_code)
);

CREATE TABLE IF NOT EXISTS accounting_employee_cost (
  employee_cost_id VARCHAR(64) NOT NULL,
  scope_code_id VARCHAR(64) NOT NULL,
  employee_number VARCHAR(60) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  position_name VARCHAR(150) NOT NULL,
  gross_salary DECIMAL(14,2) NOT NULL,
  employer_uif DECIMAL(14,2) NOT NULL DEFAULT 0,
  sdl DECIMAL(14,2) NOT NULL DEFAULT 0,
  pension_contribution DECIMAL(14,2) NOT NULL DEFAULT 0,
  medical_aid_contribution DECIMAL(14,2) NOT NULL DEFAULT 0,
  status ENUM('ACTIVE', 'INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (employee_cost_id),
  UNIQUE KEY uq_employee_scope_number (scope_code_id, employee_number),
  CONSTRAINT fk_employee_cost_scope FOREIGN KEY (scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_employee_cost_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS accounting_supplier_invoice (
  supplier_invoice_id VARCHAR(64) NOT NULL,
  scope_code_id VARCHAR(64) NOT NULL,
  supplier_name VARCHAR(180) NOT NULL,
  invoice_number VARCHAR(120) NOT NULL,
  invoice_date DATE NOT NULL,
  due_date DATE NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  file_name VARCHAR(255) NOT NULL,
  file_url VARCHAR(500) NOT NULL,
  status ENUM('UPLOADED', 'APPROVED', 'PAID', 'REJECTED') NOT NULL DEFAULT 'UPLOADED',
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (supplier_invoice_id),
  UNIQUE KEY uq_supplier_invoice (scope_code_id, supplier_name, invoice_number),
  KEY ix_supplier_invoice_due (status, due_date),
  CONSTRAINT fk_supplier_invoice_scope FOREIGN KEY (scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_supplier_invoice_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS accounting_tenant_invoice (
  tenant_invoice_id VARCHAR(64) NOT NULL,
  scope_code_id VARCHAR(64) NOT NULL,
  invoice_number VARCHAR(120) NOT NULL,
  billing_period VARCHAR(60) NOT NULL,
  issue_date DATE NOT NULL,
  due_date DATE NOT NULL,
  subscription_fee DECIMAL(14,2) NOT NULL DEFAULT 0,
  service_fees DECIMAL(14,2) NOT NULL DEFAULT 0,
  vat_rate DECIMAL(5,2) NOT NULL DEFAULT 15,
  vat_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(14,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  status ENUM('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'VOID') NOT NULL DEFAULT 'ISSUED',
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (tenant_invoice_id),
  UNIQUE KEY uq_tenant_invoice_number (invoice_number),
  KEY ix_tenant_invoice_due (scope_code_id, status, due_date),
  CONSTRAINT fk_tenant_invoice_scope FOREIGN KEY (scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_tenant_invoice_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS accounting_ledger_entry (
  ledger_entry_id VARCHAR(64) NOT NULL,
  scope_code_id VARCHAR(64) NOT NULL,
  entry_date DATE NOT NULL,
  reference VARCHAR(120) NOT NULL,
  account_code VARCHAR(40) NOT NULL,
  account_name VARCHAR(150) NOT NULL,
  account_type ENUM('ASSET', 'LIABILITY', 'EQUITY', 'INCOME', 'EXPENSE') NOT NULL,
  description VARCHAR(500) NOT NULL,
  debit DECIMAL(14,2) NOT NULL DEFAULT 0,
  credit DECIMAL(14,2) NOT NULL DEFAULT 0,
  status ENUM('DRAFT', 'POSTED', 'REVERSED') NOT NULL DEFAULT 'POSTED',
  source_document_type VARCHAR(80) NULL,
  source_document_id VARCHAR(64) NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ledger_entry_id),
  KEY ix_ledger_scope_date (scope_code_id, entry_date),
  KEY ix_ledger_reference (reference),
  CONSTRAINT fk_ledger_scope FOREIGN KEY (scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_ledger_user FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT chk_ledger_amount CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
);

CREATE TABLE IF NOT EXISTS accounting_fund_movement (
  fund_movement_id VARCHAR(64) NOT NULL,
  scope_code_id VARCHAR(64) NOT NULL,
  movement_date DATE NOT NULL,
  internal_reference VARCHAR(120) NOT NULL,
  source_name VARCHAR(180) NOT NULL,
  destination_name VARCHAR(180) NOT NULL,
  category VARCHAR(120) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  bank_reference VARCHAR(160) NULL,
  source_document_type VARCHAR(80) NULL,
  source_document_id VARCHAR(64) NULL,
  status ENUM('UNMATCHED', 'PARTIALLY_MATCHED', 'RECONCILED') NOT NULL DEFAULT 'UNMATCHED',
  reconciled_by BIGINT UNSIGNED NULL,
  reconciled_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (fund_movement_id),
  UNIQUE KEY uq_fund_movement_reference (scope_code_id, internal_reference),
  KEY ix_fund_movement_status (status, movement_date),
  CONSTRAINT fk_fund_movement_scope FOREIGN KEY (scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_fund_movement_user FOREIGN KEY (reconciled_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS accounting_payment (
  payment_id VARCHAR(64) NOT NULL,
  source_scope_code_id VARCHAR(64) NOT NULL,
  destination_scope_code_id VARCHAR(64) NOT NULL,
  payment_date DATE NOT NULL,
  payment_reference VARCHAR(160) NOT NULL,
  payment_method VARCHAR(80) NOT NULL,
  purpose VARCHAR(500) NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  status ENUM('DRAFT', 'APPROVED', 'SUBMITTED', 'RECORDED', 'FAILED', 'REVERSED') NOT NULL DEFAULT 'RECORDED',
  created_by BIGINT UNSIGNED NOT NULL,
  approved_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (payment_id),
  UNIQUE KEY uq_accounting_payment_reference (payment_reference),
  KEY ix_accounting_payment_destination (destination_scope_code_id, payment_date),
  CONSTRAINT fk_accounting_payment_source FOREIGN KEY (source_scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_accounting_payment_destination FOREIGN KEY (destination_scope_code_id) REFERENCES accounting_scope_code(scope_code_id),
  CONSTRAINT fk_accounting_payment_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_accounting_payment_approver FOREIGN KEY (approved_by) REFERENCES users(id)
);
